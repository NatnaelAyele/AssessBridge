CREATE TABLE IF NOT EXISTS assessment_identity_auth_flows (
 id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invitation_id BIGINT NOT NULL,
 candidate_user_id BIGINT NOT NULL,
 access_fingerprint CHAR(64) NOT NULL,
 state_hash CHAR(64) NOT NULL UNIQUE,
 secret_ciphertext BYTEA NOT NULL,
 status TEXT CHECK (status IN ('pending','exchanging','authenticated','completed','failed')) NOT NULL DEFAULT 'pending',
 authenticated_subject VARCHAR(255) NULL,
 authenticated_name VARCHAR(160) NULL,
 failure_reason VARCHAR(60) NULL,
 created_at TIMESTAMP(3) NOT NULL,
 expires_at TIMESTAMP(3) NOT NULL,
 authenticated_at TIMESTAMP(3) NULL,
 CONSTRAINT fk_identity_flow_invitation FOREIGN KEY(invitation_id) REFERENCES assessment_invitations(id) ON DELETE CASCADE,
 CONSTRAINT fk_identity_flow_candidate FOREIGN KEY(candidate_user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_identity_flow_owner ON assessment_identity_auth_flows (invitation_id,candidate_user_id,id);
CREATE INDEX IF NOT EXISTS idx_identity_flow_expiry ON assessment_identity_auth_flows (expires_at);

CREATE INDEX IF NOT EXISTS idx_assessment_identity_auth_flows_candidate_user_id_fk ON assessment_identity_auth_flows (candidate_user_id);
