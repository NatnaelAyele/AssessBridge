CREATE TABLE IF NOT EXISTS assessment_export_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, assessment_id BIGINT NOT NULL, invitation_id BIGINT NULL,
 actor_id BIGINT NOT NULL, actor_name VARCHAR(160) NOT NULL, format TEXT CHECK (format IN ('csv','pdf')) NOT NULL,
 publication_id BIGINT NULL, source_version VARCHAR(160) NOT NULL, filters_json JSONB NOT NULL,
 record_count INT NOT NULL, content_sha256 CHAR(64) NOT NULL, generated_at TIMESTAMP(3) NOT NULL,
 FOREIGN KEY(assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_export_assessment ON assessment_export_audit (assessment_id,generated_at);

CREATE INDEX IF NOT EXISTS idx_assessment_export_audit_actor_id_fk ON assessment_export_audit (actor_id);
