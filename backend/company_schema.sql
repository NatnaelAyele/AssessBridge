CREATE TABLE IF NOT EXISTS companies (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS company_staff_invitations (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    email CITEXT NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    role TEXT CHECK (role IN ('company_admin','employer_personnel','auditor')) NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    invited_by BIGINT NOT NULL,
    accepted_by BIGINT NULL,
    accepted_at TIMESTAMP NULL,
    revoked_at TIMESTAMP NULL,
    sent_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    FOREIGN KEY (company_id) REFERENCES companies(id),
    FOREIGN KEY (invited_by) REFERENCES users(id),
    FOREIGN KEY (accepted_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_company_invitation_email ON company_staff_invitations (company_id,email);

CREATE TABLE IF NOT EXISTS company_registration_verifications (
    user_id BIGINT NOT NULL PRIMARY KEY,
    company_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (company_id) REFERENCES companies(id)
);

CREATE TABLE IF NOT EXISTS company_account_events (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    actor_user_id BIGINT NULL,
    target_user_id BIGINT NULL,
    invitation_id BIGINT NULL,
    event_type VARCHAR(50) NOT NULL,
    expires_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    FOREIGN KEY (company_id) REFERENCES companies(id),
    FOREIGN KEY (actor_user_id) REFERENCES users(id),
    FOREIGN KEY (target_user_id) REFERENCES users(id),
    FOREIGN KEY (invitation_id) REFERENCES company_staff_invitations(id)
);
CREATE INDEX IF NOT EXISTS idx_company_events ON company_account_events (company_id,created_at);
CREATE INDEX IF NOT EXISTS idx_company_events_expiry ON company_account_events (expires_at) WHERE expires_at IS NOT NULL;

CREATE TABLE IF NOT EXISTS company_password_resets (
 user_id BIGINT PRIMARY KEY,
 token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMP NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_company_staff_invitations_accepted_by_fk ON company_staff_invitations (accepted_by);
CREATE INDEX IF NOT EXISTS idx_company_staff_invitations_invited_by_fk ON company_staff_invitations (invited_by);
CREATE INDEX IF NOT EXISTS idx_company_registration_verifications_company_id_fk ON company_registration_verifications (company_id);
CREATE INDEX IF NOT EXISTS idx_company_account_events_actor_user_id_fk ON company_account_events (actor_user_id);
CREATE INDEX IF NOT EXISTS idx_company_account_events_invitation_id_fk ON company_account_events (invitation_id);
CREATE INDEX IF NOT EXISTS idx_company_account_events_target_user_id_fk ON company_account_events (target_user_id);
