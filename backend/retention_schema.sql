CREATE TABLE IF NOT EXISTS company_retention_policies (
 company_id BIGINT PRIMARY KEY,revision INT NOT NULL DEFAULT 0,
 identity_days SMALLINT NOT NULL,monitoring_days SMALLINT NOT NULL,
 review_days SMALLINT NULL,audit_days SMALLINT NULL,
 FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS assessment_retention_policies (
 assessment_id BIGINT PRIMARY KEY,revision INT NOT NULL,
 identity_days SMALLINT NOT NULL,monitoring_days SMALLINT NOT NULL,
 review_days SMALLINT NULL,audit_days SMALLINT NULL,legacy BOOLEAN NOT NULL DEFAULT FALSE,cleanup_attempt_at TIMESTAMP NULL,
 FOREIGN KEY(assessment_id) REFERENCES assessments(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS company_retention_changes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,company_id BIGINT NOT NULL,
 revision INT NOT NULL,request_key CHAR(36) NOT NULL,payload_hash CHAR(64) NOT NULL,
 actor_id BIGINT NOT NULL,actor_name VARCHAR(254) NOT NULL,reason VARCHAR(1000) NOT NULL,
 before_json JSONB NOT NULL,after_json JSONB NOT NULL,created_at TIMESTAMP(3) NOT NULL,expires_at TIMESTAMP(3) NULL,
 CONSTRAINT uq_retention_request UNIQUE (company_id,request_key),FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS retained_assessment_audits (
 assessment_id BIGINT PRIMARY KEY,company_id BIGINT NOT NULL,
 closed_at TIMESTAMP NOT NULL,case_removed_at TIMESTAMP(3) NOT NULL,expires_at TIMESTAMP(3) NULL,
 policy_json JSONB NOT NULL,events_json JSONB NOT NULL,
 FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_retained_expiry ON retained_assessment_audits (expires_at);

CREATE INDEX IF NOT EXISTS idx_retained_assessment_audits_company_id_fk ON retained_assessment_audits (company_id);
