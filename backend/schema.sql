CREATE TABLE IF NOT EXISTS users (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NULL REFERENCES companies(id),
    full_name VARCHAR(160) NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    email CITEXT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role TEXT CHECK (role IN ('candidate', 'employer_personnel', 'auditor', 'company_admin')) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    token_id CHAR(64) NOT NULL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    CONSTRAINT fk_auth_session_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_user ON auth_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_expiry ON auth_sessions (expires_at);

CREATE TABLE IF NOT EXISTS candidate_email_verifications (
    user_id BIGINT NOT NULL PRIMARY KEY,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_email_verification_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS auth_audit (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL,
    username_attempt VARCHAR(100) NULL,
    event_type TEXT CHECK (event_type IN ('login_success', 'login_failure', 'authorization_denied', 'logout')) NOT NULL,
    source_ip VARCHAR(45) NULL,
    expires_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    CONSTRAINT fk_auth_audit_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_auth_audit_user ON auth_audit (user_id);
CREATE INDEX IF NOT EXISTS idx_auth_audit_created ON auth_audit (created_at);
CREATE INDEX IF NOT EXISTS idx_auth_audit_expiry ON auth_audit (expires_at) WHERE expires_at IS NOT NULL;

CREATE TABLE IF NOT EXISTS assessments (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NULL REFERENCES companies(id),
    employer_user_id BIGINT NOT NULL,
    request_key CHAR(36) NOT NULL UNIQUE,
    payload_hash CHAR(64) NOT NULL,
    title VARCHAR(120) NOT NULL,
    description TEXT NULL,
    internal_reference VARCHAR(60) NULL,
    duration_minutes SMALLINT NOT NULL,
    rules_text TEXT NULL,
    identity_policy TEXT NULL,
    questions_json JSONB NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    CONSTRAINT fk_assessment_employer FOREIGN KEY (employer_user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_assessment_employer ON assessments (employer_user_id);

CREATE TABLE IF NOT EXISTS assessment_invitations (
