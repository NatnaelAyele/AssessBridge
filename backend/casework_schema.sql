CREATE TABLE IF NOT EXISTS assessment_case_notes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id BIGINT NOT NULL,revision INT NOT NULL,
 request_key CHAR(36) NOT NULL,payload_hash CHAR(64) NOT NULL,body TEXT NOT NULL,reference_kind VARCHAR(20) NULL,reference_key VARCHAR(100) NULL,
 actor_id BIGINT NOT NULL,actor_name VARCHAR(160) NOT NULL,created_at TIMESTAMP(3) NOT NULL,
 CONSTRAINT uq_note_request UNIQUE (session_id,request_key),FOREIGN KEY(session_id) REFERENCES assessment_exam_sessions(id) ON DELETE CASCADE,FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS assessment_audit_outcomes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id BIGINT NOT NULL,kind TEXT CHECK (kind IN ('needs_attention','audited')) NOT NULL,
 reason TEXT NOT NULL,evidence_version CHAR(64) NOT NULL,actor_id BIGINT NOT NULL,actor_name VARCHAR(160) NOT NULL,
 request_key CHAR(36) NULL,payload_hash CHAR(64) NULL,created_at TIMESTAMP(3) NOT NULL,
 CONSTRAINT uq_outcome_request UNIQUE (session_id,request_key),FOREIGN KEY(session_id) REFERENCES assessment_exam_sessions(id) ON DELETE CASCADE,FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS assessment_publication_holds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,assessment_id BIGINT NOT NULL,kind TEXT CHECK (kind IN ('held','resolved')) NOT NULL,
 reason TEXT NOT NULL,actor_id BIGINT NOT NULL,actor_name VARCHAR(160) NOT NULL,request_key CHAR(36) NOT NULL,payload_hash CHAR(64) NOT NULL,created_at TIMESTAMP(3) NOT NULL,
 CONSTRAINT uq_hold_request UNIQUE (assessment_id,request_key),FOREIGN KEY(assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,FOREIGN KEY(actor_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_assessment_case_notes_actor_id_fk ON assessment_case_notes (actor_id);
CREATE INDEX IF NOT EXISTS idx_assessment_audit_outcomes_actor_id_fk ON assessment_audit_outcomes (actor_id);
CREATE INDEX IF NOT EXISTS idx_assessment_publication_holds_actor_id_fk ON assessment_publication_holds (actor_id);
